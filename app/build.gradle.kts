// Release signing comes from keystore.properties (git-ignored) or environment variables.
// Without either, release builds fall back to the debug key so anyone can build and run them.
val signing = Properties().apply {
    rootProject.file("keystore.properties").takeIf { it.exists() }?.inputStream()?.use { load(it) }
}
fun signingValue(key: String, env: String): String? = signing.getProperty(key) ?: System.getenv(env)
val releaseStore = signingValue("storeFile", "SIGNING_STORE_FILE")

android {
    namespace = "com.visiuun.inkwell"
    compileSdk = 37

    defaultConfig {
        applicationId = "com.visiuun.inkwell"
        minSdk = 24
        targetSdk = 36
        versionCode = 4
        versionName = "1.1.1"
        buildConfigField("String", "UPDATE_REPO", "\"visiuun/inkwell\"")
    }

    signingConfigs {
        if (releaseStore != null) {
            create("release") {
                storeFile = rootProject.file(releaseStore)
                storePassword = signingValue("storePassword", "SIGNING_STORE_PASSWORD")
                keyAlias = signingValue("keyAlias", "SIGNING_KEY_ALIAS")
                keyPassword = signingValue("keyPassword", "SIGNING_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = signingConfigs.findByName("release") ?: signingConfigs.getByName("debug")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
