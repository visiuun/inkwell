URL = "https://fonts.gstatic.com/s/i/short-term/release/materialsymbolsrounded/{name}/{variant}/24px.svg"

out = [
    "// Generated by tools/gen_symbols.py from Material Symbols Rounded (Apache License 2.0). Do not edit by hand.",
    "package com.visiuun.inkwell.ui.theme",
    "",
    "import androidx.compose.ui.graphics.SolidColor",
    "import androidx.compose.ui.graphics.Color",
    "import androidx.compose.ui.graphics.vector.ImageVector",
    "import androidx.compose.ui.graphics.vector.addPathNodes",
    "import androidx.compose.ui.graphics.vector.group",
    "import androidx.compose.ui.unit.dp",
    "",
    "private fun symbol(name: String, vararg paths: String): ImageVector =",
    "    ImageVector.Builder(name, 24.dp, 24.dp, 960f, 960f).apply {",
    "        // Material Symbols use a 0 -960 960 960 viewBox.",
    "        group(translationY = 960f) {",
    "            paths.forEach { addPath(pathData = addPathNodes(it), fill = SolidColor(Color.Black)) }",
    "        }",
    "    }.build()",
    "",
    "/** Material Symbols Rounded, the current Material icon set. */",
    "object Sym {",
]
for kname, (name, variant) in ICONS.items():
    svg = urllib.request.urlopen(URL.format(name=name, variant=variant), timeout=30).read().decode()
    paths = re.findall(r'<path[^>]* d="([^"]+)"', svg)
    if not paths:
        raise SystemExit("no path for " + name)
    args = ", ".join('"%s"' % p for p in paths)
    out.append('    val %s: ImageVector by lazy { symbol("%s", %s) }' % (kname, name, args))
out.append("}")
open(sys.argv[1], "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print("wrote", len(ICONS), "symbols")
